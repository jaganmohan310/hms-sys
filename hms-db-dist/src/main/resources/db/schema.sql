-- ===================================================================
-- PulseSquare Enterprise HMS Consolidated DDL Schema
-- Used for jOOQ offline metamodel code generation & reference
-- Dialect: IBM Db2 Enterprise / ANSI SQL
-- ===================================================================

-- 1. Roles Definition Table
CREATE TABLE hms_roles (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL PRIMARY KEY,
    name VARCHAR(50) NOT NULL UNIQUE,
    description VARCHAR(255),
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL
);

-- 2. Enterprise Users Table
CREATE TABLE hms_users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL PRIMARY KEY,
    username VARCHAR(50) NOT NULL UNIQUE,
    email VARCHAR(100) NOT NULL UNIQUE,
    password_hash VARCHAR(100) NOT NULL,
    full_name VARCHAR(100) NOT NULL,
    contact_number VARCHAR(20),
    department VARCHAR(80),
    account_enabled BOOLEAN DEFAULT TRUE NOT NULL,
    account_locked BOOLEAN DEFAULT FALSE NOT NULL,
    failed_login_attempts INT DEFAULT 0 NOT NULL,
    last_login_at TIMESTAMP,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL
);

-- 3. User-to-Roles Relationship Table (Many-to-Many)
CREATE TABLE hms_user_roles (
    user_id BIGINT NOT NULL,
    role_id BIGINT NOT NULL,
    PRIMARY KEY (user_id, role_id),
    CONSTRAINT fk_user_roles_user FOREIGN KEY (user_id) REFERENCES hms_users(id) ON DELETE CASCADE,
    CONSTRAINT fk_user_roles_role FOREIGN KEY (role_id) REFERENCES hms_roles(id) ON DELETE CASCADE
);

-- 4. Enterprise JWT Refresh Tokens Table
CREATE TABLE hms_refresh_tokens (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL PRIMARY KEY,
    token VARCHAR(255) NOT NULL UNIQUE,
    user_id BIGINT NOT NULL,
    expiry_date TIMESTAMP NOT NULL,
    revoked BOOLEAN DEFAULT FALSE NOT NULL,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT fk_refresh_token_user FOREIGN KEY (user_id) REFERENCES hms_users(id) ON DELETE CASCADE
);

-- 5. Enterprise Security & Audit Log Table (HIPAA / Compliance)
CREATE TABLE hms_audit_logs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL PRIMARY KEY,
    action VARCHAR(50) NOT NULL,
    username VARCHAR(50),
    ip_address VARCHAR(45),
    user_agent VARCHAR(255),
    status VARCHAR(20) NOT NULL,
    details VARCHAR(500),
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL
);

-- 6. Sequence for Medical Record Number (MRN) generation
CREATE SEQUENCE seq_hms_mrn START WITH 10001 INCREMENT BY 1;

-- 7. Master Patient Index (MPI) Table
CREATE TABLE hms_patients (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL PRIMARY KEY,
    mrn VARCHAR(50) NOT NULL UNIQUE,
    title VARCHAR(20) DEFAULT 'Mr',
    first_name VARCHAR(100) NOT NULL,
    middle_name VARCHAR(100),
    last_name VARCHAR(100) NOT NULL,
    gender VARCHAR(20) NOT NULL,
    date_of_birth DATE,
    age_years INT,
    age_months INT,
    age_days INT,
    blood_group VARCHAR(10),
    contact_number VARCHAR(20),
    email VARCHAR(100),
    marital_status VARCHAR(30),
    religion VARCHAR(50),
    address VARCHAR(255),
    city VARCHAR(100),
    state VARCHAR(100),
    country VARCHAR(100) DEFAULT 'INDIA',
    zip_code VARCHAR(20),
    referral_doctor VARCHAR(100),
    department VARCHAR(100),
    registration_fee DECIMAL(10, 2) DEFAULT 0.00,
    payment_type VARCHAR(30) DEFAULT 'Cash',
    active BOOLEAN DEFAULT TRUE NOT NULL,
    registered_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL
);

-- Indexes for Universal Multi-Module Search
CREATE INDEX idx_users_username ON hms_users(username);
CREATE INDEX idx_users_email ON hms_users(email);
CREATE INDEX idx_refresh_token ON hms_refresh_tokens(token);
CREATE INDEX idx_audit_created_at ON hms_audit_logs(created_at);
CREATE INDEX idx_audit_username ON hms_audit_logs(username);
CREATE INDEX idx_patient_mrn ON hms_patients(mrn);
CREATE INDEX idx_patient_contact ON hms_patients(contact_number);
CREATE INDEX idx_patient_name ON hms_patients(first_name, last_name);

-- 7. Official All-India Pincode Directory Table
CREATE TABLE hms_pincodes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL PRIMARY KEY,
    pincode VARCHAR(10) NOT NULL,
    office_name VARCHAR(150) NOT NULL,
    office_type VARCHAR(20),
    delivery_status VARCHAR(50),
    division_name VARCHAR(100),
    region_name VARCHAR(100),
    circle_name VARCHAR(100),
    district VARCHAR(100) NOT NULL,
    state_name VARCHAR(100) NOT NULL,
    latitude VARCHAR(50),
    longitude VARCHAR(50)
);

CREATE INDEX idx_pincode_pin ON hms_pincodes(pincode);
CREATE INDEX idx_pincode_state ON hms_pincodes(state_name);
CREATE INDEX idx_pincode_dist ON hms_pincodes(district);
CREATE INDEX idx_pincode_state_dist ON hms_pincodes(state_name, district);
